import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const source = readFileSync(process.argv[2], 'utf8');
if (createHash('sha256').update(source).digest('hex') !== '4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4') {
  throw new Error('Expected Unicode 17.0.0 DerivedBidiClass.txt');
}

// L is the default, including unassigned code points. Apply block defaults
// before explicit entries; otherwise marks and digits can become strong RTL.
const classes = new Uint8Array(0x110000);
const defaults = {Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET'};
function fill(start, end, kind) {
  classes.fill(kind === 'L' ? 0 : kind === 'R' || kind === 'AL' ? 1 : 2, parseInt(start, 16), parseInt(end ?? start, 16) + 1);
}
for (const [, start, end, kind] of source.matchAll(/^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/gm)) {
  if (!(kind in defaults)) throw new Error(`Unknown bidi default: ${kind}`);
  fill(start, end, defaults[kind]);
}
for (const [, start, end, kind] of source.matchAll(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/gm)) {
  fill(start, end, kind);
}

function pattern(matches) {
  const ranges = [];
  for (let start = 0; start < classes.length; start++) {
    if (!matches(classes[start])) continue;
    let end = start;
    while (end + 1 < classes.length && matches(classes[end + 1])) end++;
    const escape = code => `\\u{${code.toString(16)}}`;
    ranges.push(start === end ? escape(start) : `${escape(start)}-${escape(end)}`);
    start = end;
  }
  return `/[${ranges.join('')}]/u`;
}


export function migrateReceiverStyle(value: unknown): unknown {
  if (value === 'sumi-mountains' || value === 'moonlit-tide') {
    return 'sumi-ocean';
  }

  return typeof value === 'string' && retiredReceiverStyles.has(value) ? defaultReceiverStyle : value;
}
